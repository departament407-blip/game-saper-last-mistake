export function getLanguage(): Language {
  const stored = localStorage.getItem(STORAGE_KEY);
  return stored === "en" || stored === "es" || stored === "ru" ? stored : "ru";
}

export function setLanguage(language: Language): void {
  localStorage.setItem(STORAGE_KEY, language);
}

export function t(key: string, values: Record<string, string | number> = {}): string {
  const template = dictionaries[getLanguage()][key] ?? dictionaries.ru[key] ?? key;
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template
  );
}

export function getModeLabel(mode: CampaignMode): string {
  return t(`mode.${mode}`);
}

export function getBiomeLabel(id: BiomeId): string {
  return t(`biome.${id}`);
}

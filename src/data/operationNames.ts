export function getOperationName(biomeId: BiomeId, tier: OperationTier, randomValue: number): string {
  const range = getNameRange(tier);
  const names = OPERATION_NAMES[biomeId];
  const index = range.start + Math.floor(Math.max(0, Math.min(0.999999, randomValue)) * range.length);
  return names[index] ?? names[0];
}

function getNameRange(tier: OperationTier): { start: number; length: number } {
  switch (tier) {
    case "easy":
      return { start: 0, length: 5 };
    case "medium":
      return { start: 5, length: 5 };
    case "hard":
      return { start: 10, length: 5 };
    case "peak":
    case "special":
    case "endgame":
      return { start: 15, length: 5 };
  }
}

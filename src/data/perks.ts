export function getPerk(id: string): Perk | undefined {
  return PERKS.find((perk) => perk.id === id);
}

export function getCharacterPerks(characterId: string): Perk[] {
  return PERKS.filter((perk) => perk.characterId === characterId).sort((a, b) => a.unlockMinXp - b.unlockMinXp);
}

export function getPerkDescription(perk: Perk, mode: CampaignMode, tier = 1): string {
  return getPerkEffectDescription(perk.id, mode, tier);
}

export function getPerkEffectDescription(perkId: string, mode: CampaignMode, tier = 1): string {
  const effects = EFFECTS[perkId];
  const effect = effects?.[clampTier(tier) - 1];

  if (!effect) {
    const perk = getPerk(perkId);
    return perk ? (mode === "solo" ? perk.soloDescription : perk.squadDescription) : "";
  }

  return mode === "solo" ? effect.solo : effect.squad;
}

export function getNextPerkEffectDescription(perkId: string, mode: CampaignMode, tier: number): string | null {
  const nextTier = clampTier(tier + 1);

  if (nextTier === clampTier(tier)) {
    return null;
  }

  return getPerkEffectDescription(perkId, mode, nextTier);
}

export function clampTier(tier: number): 1 | 2 | 3 {
  if (tier >= 3) {
    return 3;
  }

  if (tier <= 1) {
    return 1;
  }

  return 2;
}

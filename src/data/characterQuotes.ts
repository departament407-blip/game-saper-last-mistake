export function pickCharacterQuote(
  characterId: string,
  eventType: CharacterQuoteEvent,
  playerName: string,
  previousQuote: string | null
): string | null {
  const pool = CHARACTER_QUOTES[characterId]?.[eventType];

  if (!pool || pool.length === 0) {
    return null;
  }

  const filtered = previousQuote ? pool.filter((quote) => quote !== previousQuote) : pool;
  const source = filtered.length > 0 ? filtered : pool;
  const quote = source[Math.floor(Math.random() * source.length)] ?? source[0];

  return quote.replaceAll("{playerName}", playerName);
}
